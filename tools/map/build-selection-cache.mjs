// Offline geometry preparation: use exactly the runtime contour algorithm.
import { readFileSync, writeFileSync } from 'node:fs';
import { gunzipSync, gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { GLTFLoader } from '../../assets/institutions/ifpr-pgua/map/viewer/vendor/loaders/GLTFLoader.js';
import * as THREE from '../../assets/institutions/ifpr-pgua/map/viewer/vendor/three.module.min.js';
import { createGeometrySelectionOutline, collectSelectionWindowMeshes } from '../../assets/institutions/ifpr-pgua/map/viewer/selection_geometry_outline.js';
import { createInteriorNavigation } from '../../assets/institutions/ifpr-pgua/map/viewer/interior_navigation.js';

const base = new URL('../../assets/institutions/ifpr-pgua/map/', import.meta.url);
const bytes = gunzipSync(readFileSync(new URL('campus_exterior_standard.glb.gz', base)));
const metadata = JSON.parse(readFileSync(new URL('campus_map.json', base), 'utf8'));
const loader = new GLTFLoader();
// Texture pixels are irrelevant to edges. Keep all material names/groups.
loader.register(() => ({ name: 'OUTLINE_OFFLINE', loadTexture: () => Promise.resolve(null) }));
const { scene: model } = await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
const findNode = (root, name) => {
  const named = root.getObjectByName(name);
  if (named) return named;
  let found = null;
  root.traverse(node => { if (!found && node.userData?.name === name) found = node; });
  return found;
};
const campus = new THREE.Scene(); campus.add(model);
const interiors = createInteriorNavigation(model, metadata.zones, findNode, campus);
const windows = collectSelectionWindowMeshes(model);
const exteriorNodes = new Set(metadata.zones.map(zone => findNode(model, zone.nodeName)));
const outline = createGeometrySelectionOutline(null, {
  windowNodesFor: node => exteriorNodes.has(node) ? windows : [],
});
const encode = array => Buffer.from(array.buffer, array.byteOffset, array.byteLength).toString('base64');
const cache = {};
const nodes = metadata.zones.map(zone => findNode(model, zone.nodeName));
nodes.push(...[...interiors.floors.values()].map(floor => floor.group));
for (const node of nodes) {
  if (!node) throw new Error('Missing outline node.');
  const entry = outline.prepare(node);
  cache[node.name] = {
    maskPositions: encode(entry.maskGeometry.getAttribute('position').array),
    maskIndices: encode(Uint32Array.from(entry.maskGeometry.index.array)),
    edgeStart: encode(entry.geometry.getAttribute('edgeStart').array),
    edgeEnd: encode(entry.geometry.getAttribute('edgeEnd').array),
    sphere: [...entry.sphere.center.toArray(), entry.sphere.radius],
    windowRows: entry.windowRows, filledHoles: entry.filledHoles, facadeEnvelopes: entry.facadeEnvelopes,
  };
  console.log(`${node.name}: ${entry.count} edges`);
}
const hash = createHash('sha256').update(bytes).digest('hex');
const layout = JSON.stringify(metadata.zones.map(zone => [zone.nodeName,
  (zone.floors ?? []).map(floor => [floor.id, floor.nodeNames, floor.spaces.map(space => space.nodeName)])]));
const payload = gzipSync(Buffer.from(JSON.stringify(cache)), { level: 9 }).toString('base64');
writeFileSync(new URL('viewer/selection_cache_data.js', base),
  `// Generated by tools/map/build-selection-cache.mjs; rebuild after changing the GLB.\n` +
  `export const selectionCacheModelHash = ${JSON.stringify(hash)};\n` +
  `export const selectionCacheLayout = ${JSON.stringify(layout)};\n` +
  `export const selectionCachePayload = ${JSON.stringify(payload)};\n`);
console.log(JSON.stringify({ compressedBytes: payload.length * 3 / 4, nodes: nodes.length, modelHash: hash }));
outline.dispose(); interiors.dispose();
